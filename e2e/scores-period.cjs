// Hand-expected, fictional records: period isolation, locked app ratings, coverage and navigation.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const [URL = 'http://127.0.0.1:4178/', OUT = 'docs/design/screens'] = process.argv.slice(2);
const ok = (condition, label) => { if (!condition) throw Error('FAIL: ' + label); console.log('ok ' + label); };
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'America/New_York', reducedMotion: 'reduce' });
  await ctx.clock.install({ time: new Date('2026-01-30T12:00:00-05:00') });
  await ctx.clock.setFixedTime(new Date('2026-01-30T12:00:00-05:00'));
  const page = await ctx.newPage(); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(URL);
  await page.getByRole('button', { name: 'Try demo data' }).click();
  await page.getByRole('button', { name: /^7 Hitting/ }).waitFor();
  await page.evaluate(async () => {
    const anchor = Date.parse('2026-01-01T00:00:00-05:00'), day = 86400000, window = 14 * day;
    const db = await new Promise((resolve, reject) => { const request = indexedDB.open('cmai-tracker'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error); });
    await new Promise((resolve, reject) => {
      const tx = db.transaction(['patients','observations','checkins','reviews'], 'readwrite');
      tx.objectStore('patients').put({ id:'P-TEST-A', anchor });
      tx.objectStore('patients').put({ id:'P-TEST-B', anchor: anchor + 2*window });
      tx.objectStore('patients').put({ id:'P-QUIET', anchor });
      for (const offset of [1, 60001, 120001, 180001, window-1]) tx.objectStore('observations').add({patientId:'P-TEST-A',itemId:7,at:anchor+offset,loggedAt:anchor+offset});
      for (const [itemId, offset] of [[8,window],[9,2*window],[9,2*window+60000]]) tx.objectStore('observations').add({patientId:'P-TEST-A',itemId,at:anchor+offset,loggedAt:anchor+offset});
      tx.objectStore('observations').add({patientId:'P-TEST-B',itemId:1,at:anchor+2*window,loggedAt:anchor+2*window});
      for (const id of ['P-TEST-A','P-QUIET']) tx.objectStore('checkins').put({key:id+'|'+(anchor+day),patientId:id,day:anchor+day,at:anchor+day});
      // Old day-14 reviews on file (from before D-14). The app's ratings must ignore them.
      for (const [itemId,choice,derived] of [[3,9,1],[7,8,1],[8,4,2]]) tx.objectStore('reviews').put({key:`P-TEST-A|${anchor+window}|${itemId}`,patientId:'P-TEST-A',windowStart:anchor+window,itemId,choice,derived,reviewedAt:anchor+2*window});
      tx.oncomplete=resolve; tx.onerror=()=>reject(tx.error);
    }); db.close(); localStorage.setItem('cmai-patient','P-TEST-A');
  });
  await page.reload(); await page.getByRole('button', { name:'Scores', exact:true }).click();
  await page.getByRole('heading', { name:'Period 2 scores',exact:true }).waitFor();
  const total = page.locator('.score-total-value');
  ok(await total.textContent() === '30', 'P2 total is hand-expected 30 from logs alone, all 29 items');
  ok((await page.locator('#sc-total').textContent()).includes('29 of 29 ratings'), 'old review codes 8 and 9 do not drop items from the total');
  ok(await page.locator('.period-scores').first().locator('tbody tr').count() === 1, 'P2 shows only its one logged behavior');
  const kicking = page.locator('#sc-behaviors tr[data-behavior="8"]');
  ok((await kicking.textContent()).includes('App-derived from logs'), 'rating source is the app');
  ok(await kicking.locator('td').first().textContent() === '2' && await kicking.locator('td').last().textContent() === '1', 'P2 kicking: app rating 2 from one log; the old review of 4 is ignored');
  ok((await kicking.locator('th').textContent()).includes('About the same (was 1)'), 'P2 kicking says how it moved since P1 (1 to 2)');
  ok((await page.locator('#sc-total').textContent()).includes('13 unlogged days'), 'P2 coverage stays scoped');
  ok((await page.locator('.score-group-values').textContent()).includes('1.11'), 'P2 aggressive mean uses app ratings only');
  ok(!(await page.locator('#sc-history table').count()), 'history data is absent until explicitly opened');
  await page.screenshot({path:path.join(OUT,'scores-period-layout-check.png')});
  const totalBox = await total.boundingBox(), firstBox = await page.locator('#sc-behaviors tbody tr').first().boundingBox();
  ok(totalBox.y < 760 && firstBox.y < 760, `total and behavior scores begin above bottom tabs (total ${totalBox.y}, behavior ${firstBox.y})`);
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'phone has no page-level horizontal overflow');
  await page.getByRole('button',{name:'Previous period',exact:true}).click();
  await page.getByRole('heading',{name:'Period 1 scores',exact:true}).waitFor();
  ok(await total.textContent()==='32', 'P1 total is hand-expected 32');
  ok(page.url().endsWith('#/scores/p1'), 'the chosen period is in the URL');
  ok((await page.locator('.score-range').textContent()).includes('period 3 is in progress'), 'an earlier period says which one is in progress');
  ok(await page.locator('#sc-behaviors tbody tr').count()===1, 'P1 never inherits P2/P3 behaviors');
  ok(await page.locator('#sc-behaviors tr[data-behavior="7"] td').last().textContent()==='5', 'end-exclusive boundary assigns fifth hitting log to P1');
  ok((await page.locator('#sc-total').textContent()).includes('11 unlogged days'), 'quiet-day check-in counts as covered; missed days remain unknown');
  await page.reload(); await page.getByRole('heading',{name:'Period 1 scores',exact:true}).waitFor();
  ok(await total.textContent()==='32', 'reload preserves selected period for this patient');
  await page.locator('nav.tabs button',{hasText:'Log'}).click(); await page.getByRole('button',{name:'Scores',exact:true}).click();
  await page.getByRole('heading',{name:'Period 1 scores',exact:true}).waitFor(); ok(true,'leaving and returning preserves selected period');
  await page.getByRole('button',{name:'Next period',exact:true}).focus(); await page.keyboard.press('Enter');
  await page.getByRole('heading',{name:'Period 2 scores',exact:true}).waitFor(); ok(true,'keyboard changes the period');
  await page.getByRole('button',{name:'Next period',exact:true}).click();
  await page.getByRole('heading',{name:'Period 3 scores',exact:true}).waitFor();
  ok(await total.textContent()==='31' && (await page.locator('#sc-total').textContent()).includes('so far'), 'open-period total is provisional 31');
  ok(await page.locator('#sc-behaviors tbody tr').count()===1 && await page.locator('#sc-behaviors tr[data-behavior="9"]').count()===1, 'open-period behavior list is isolated');
  await page.getByText('Compare finished periods (2)',{exact:true}).click();
  await page.locator('#sc-history table').first().waitFor();
  ok(await page.locator('#sc-history .heat thead th').count()===3, 'history excludes open P3');
  ok(await page.locator('#sc-history .heat tbody tr').count() < 30, 'history lists only behaviors seen, like the table above');
  ok((await page.locator('#sc-history').textContent()).includes('32') && (await page.locator('#sc-history').textContent()).includes('30'), 'historical totals remain available');
  await page.getByRole('button',{name:'Previous period',exact:true}).click();
  ok(!(await page.locator('#sc-history table').count()), 'switching period closes comparison');
  await page.getByRole('button',{name:/Choose patient$/}).click();
  await page.getByRole('dialog',{name:'Choose patient',exact:true}).getByRole('button',{name:/^P-TEST-B/}).click();
  await page.getByRole('heading',{name:'Period 1 scores',exact:true}).waitFor();
  ok(await total.textContent()==='30' && await page.locator('#sc-behaviors tr[data-behavior="1"]').count()===1, 'switching patient cannot show the previous patient scores');
  await page.getByRole('button',{name:/Choose patient$/}).click();
  await page.getByRole('dialog',{name:'Choose patient',exact:true}).getByRole('button',{name:/^P-QUIET/}).click();
  await page.getByRole('heading',{name:'Period 2 scores',exact:true}).waitFor();
  ok(await total.textContent()==='29' && (await page.locator('#sc-behaviors').textContent()).includes('No behaviors logged'), 'quiet-only patient can view scores with coverage caveat');
  await page.getByRole('button',{name:/Choose patient$/}).click();
  await page.getByRole('dialog',{name:'Choose patient',exact:true}).getByRole('button',{name:/^P-TEST-A/}).click();
  await page.getByRole('heading',{name:'Period 2 scores',exact:true}).waitFor();
  await page.getByRole('button',{name:'Show all 29 behaviors'}).click();
  ok(await page.locator('#sc-behaviors tbody tr').count()===29, 'all 29 behavior ratings remain reachable');
  await page.getByRole('button',{name:'Show logged behaviors'}).click();
  const axe = fs.readFileSync(require.resolve('axe-core/axe.min.js'),'utf8');
  const audits = [];
  for (const [name,theme,contrast] of [['light','light','standard'],['dark','dark','standard'],['light-high','light','high'],['dark-high','dark','high']]) {
    await page.evaluate(([t,c])=>{localStorage.setItem('cmai-theme',t);localStorage.setItem('cmai-contrast',c);},[theme,contrast]);
    // Use resolved theme attributes, matching the app resolver, without altering scoring data.
    await page.evaluate(([t,c])=>{document.documentElement.dataset.theme=t;document.documentElement.dataset.contrast=c;},[theme,contrast]);
    await page.evaluate(()=>scrollTo(0,0)); await page.waitForTimeout(200);
    await page.screenshot({path:path.join(OUT,`scores-period-after-${name}.png`),fullPage:true});
    await page.addScriptTag({content:axe});
    const result=await page.evaluate(()=>axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']}}));
    audits.push({name,violations:result.violations,incomplete:result.incomplete.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))});
    fs.writeFileSync(path.join(OUT,'scores-period-axe.json'),JSON.stringify(audits,null,2));
    for (const v of result.violations) console.error(v.id, v.nodes.map(n=>({target:n.target,summary:n.failureSummary})));
    ok(result.violations.length===0,`${name}: zero axe violations`);
    await page.getByText('Compare finished periods (2)',{exact:true}).click();
    const history=await page.evaluate(()=>axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']}}));
    audits.push({name:name+'-history',violations:history.violations});
    ok(history.violations.length===0,`${name}: expanded history has zero axe violations`);
    await page.getByText('Compare finished periods (2)',{exact:true}).click();
  }
  fs.writeFileSync(path.join(OUT,'scores-period-axe.json'),JSON.stringify(audits,null,2));
  await page.setViewportSize({width:1280,height:900}); await page.screenshot({path:path.join(OUT,'scores-period-after-desktop.png'),fullPage:true});
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'desktop has no page overflow');
  await page.setViewportSize({width:320,height:700});
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'320px width has no page overflow');
  await page.emulateMedia({forcedColors:'active'}); ok(await total.isVisible(),'total remains visible in forced colors');
  await page.reload(); await page.getByRole('heading',{name:'Period 2 scores',exact:true}).waitFor();
  await page.waitForTimeout(1500); await ctx.setOffline(true); await page.reload();
  await page.getByRole('heading',{name:'Period 2 scores',exact:true}).waitFor();
  ok(await total.textContent()==='30','offline reload retains period and scores');
  ok(errors.length===0,'no browser exceptions: '+JSON.stringify(errors));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
